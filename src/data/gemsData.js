// O(1) Fast Lookup Map by uppercase country ISO code
export const gemsByCountryId = new Map(
  gemsData.map((country) => [country.id.toUpperCase(), country])
);

export function getCountryById(id) {
  if (!id) return null;
  return gemsByCountryId.get(id.toUpperCase()) || null;
}

// Classify gem into kid-friendly categories for the Explorer Modal
export function getGemCategory(gem) {
  if (!gem) return 'all';
  if (gem.mohs >= 8) return 'precious';
  if (gem.tumblerStatus === 'great') return 'tumbler';
  if (gem.inNatGeoKit) return 'natgeo';
  return 'magical';
}

